def build_full_dataset():
    all_docs = []
    seen_slugs = set()

    def add(name, state, district, city, category, subcategory, lat, lon,
            desc, seasons, diff, tags, pop=None, rating=None, efee=None):
        slug_base = slugify(f"{name}-{state}")
        slug = slug_base
        counter = 2
        while slug in seen_slugs:
            slug = f"{slug_base}-{counter}"
            counter += 1
        seen_slugs.add(slug)

        fee_val = efee if efee is not None else fee()
        pop_val = pop if pop is not None else round(random.uniform(55, 100), 1)
        rating_val = rating if rating is not None else round(random.uniform(3.5, 5.0), 1)

        doc = {
            "name": name,
            "slug": slug,
            "state": state,
            "district": district,
            "city": city,
            "category": category,
            "subcategory": subcategory,
            "description": desc,
            "latitude": round(lat, 6),
            "longitude": round(lon, 6),
            "bestSeason": seasons,
            "difficulty": diff,
            "entryFee": fee_val,
            "rating": rating_val,
            "imageUrl": f"https://images.azaadsafar.com/destinations/{slug}.jpg",
            "tags": tags,
            "popularityScore": pop_val,
        }
        all_docs.append(doc)

    # 1. Seed entries
    for s in DESTINATIONS_SEED:
        add(s["name"], s["state"], s["district"], s["city"],
            s["category"], s["subcategory"],
            s["lat"], s["lon"], s["desc"],
            s["seasons"], s["diff"], s["tags"])

    # 2. Expanded variants from seeds
    for s in DESTINATIONS_SEED:
        cat = s["category"]
        templates = CATEGORY_TEMPLATES.get(cat, [])
        for tpl in templates:
            tname = tpl[0].format(name=s["name"])
            tdesc = tpl[1].format(name=s["name"])
            ttags = list(set(s["tags"][:2] + tpl[2]))
            add(tname, s["state"], s["district"], s["city"],
                cat, s["subcategory"],
                jitter(s["lat"]), jitter(s["lon"]), tdesc,
                s["seasons"], s["diff"], ttags)

    # 3. Generic extras
    for state, entries in GENERIC_EXTRA.items():
        for e in entries:
            name, city, district, category, subcategory, lat, lon, tags = e
            desc = f"{name} is a notable attraction in {city}, {state}; popular with travellers exploring the region."
            add(name, state, district, city, category, subcategory,
                lat, lon, desc,
                ["October","November","December","January","February","March"],
                random.choice(["Easy","Moderate"]), tags)

    # 4. Systematic filler: one entry per state × multiple categories
    STATE_COORDS = {
        "Andhra Pradesh": (15.9129, 79.7400), "Arunachal Pradesh": (27.0, 93.6),
        "Assam": (26.2, 92.9), "Bihar": (25.0, 85.3), "Chhattisgarh": (21.3, 81.7),
        "Goa": (15.3, 74.1), "Gujarat": (22.3, 72.6), "Haryana": (29.1, 76.1),
        "Himachal Pradesh": (31.9, 77.1), "Jharkhand": (23.6, 85.3),
        "Karnataka": (14.5, 75.7), "Kerala": (10.5, 76.3),
        "Madhya Pradesh": (23.5, 78.0), "Maharashtra": (19.7, 75.7),
        "Manipur": (24.7, 94.0), "Meghalaya": (25.5, 91.5),
        "Mizoram": (23.2, 92.9), "Nagaland": (26.2, 94.1),
        "Odisha": (20.9, 84.9), "Punjab": (31.1, 75.3),
        "Rajasthan": (27.0, 74.2), "Sikkim": (27.5, 88.5),
        "Tamil Nadu": (11.1, 78.7), "Telangana": (17.4, 79.1),
        "Tripura": (23.9, 91.5), "Uttar Pradesh": (26.8, 80.9),
        "Uttarakhand": (30.1, 79.3), "West Bengal": (23.0, 87.9),
        "Andaman & Nicobar Islands": (11.7, 92.7),
        "Chandigarh": (30.7, 76.8), "Delhi": (28.6, 77.2),
        "Jammu & Kashmir": (33.7, 75.3), "Ladakh": (34.2, 77.6),
        "Lakshadweep": (10.6, 72.6), "Puducherry": (11.9, 79.8),
    }

    FILLER_CATS = [
        ("Scenic Viewpoint","Panoramic Viewpoint"),
        ("Trekking","Forest Trail"),
        ("Lake","Reservoir"),
        ("Cave","Natural Cave"),
        ("Wildlife Sanctuary","Forest Reserve"),
        ("Museum","Regional Museum"),
        ("Religious Destination","Pilgrimage Site"),
        ("Adventure","Camping Site"),
        ("Historical Monument","Heritage Site"),
        ("Beach","Coastal Spot"),
    ]
    DIFFS = ["Easy","Moderate","Difficult","Easy","Easy"]
    counter_by_state = {}

    needed = 5100 - len(all_docs)
    per_state = max(1, needed // len(STATE_COORDS))

    for state, (base_lat, base_lon) in STATE_COORDS.items():
        n = counter_by_state.get(state, 0)
        while n < per_state:
            cat, subcat = random.choice(FILLER_CATS)
            idx = n + 1
            name = f"{state} {cat} Site {idx:02d}"
            desc = (f"A beautiful {cat.lower()} located in {state}, "
                    f"attracting visitors for its natural scenery and local cultural significance.")
            tags = [state.lower().replace(" ","-"), cat.lower().replace(" ","-"),
                    subcat.lower().replace(" ","-"), "offbeat", "local gem"]
            add(name, state, f"{state} District {(idx%5)+1}", state,
                cat, subcat,
                jitter(base_lat, 1.5), jitter(base_lon, 1.5), desc,
                ["October","November","December","January","February","March"],
                random.choice(DIFFS), tags)
            n += 1
        counter_by_state[state] = n

    print(f"Total destinations generated: {len(all_docs)}")
    return all_docs

